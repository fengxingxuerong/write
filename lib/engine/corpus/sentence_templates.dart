/// - `{action}`  动作
/// - `{emotion}` 情绪
/// - `{dialogue}` 带 `{name}` 的对话片段
///
/// 内容均为自研或公有领域的通用网文句式，严禁打包受版权文本。
/// 每个题材 = 通用池（≥60）+ 题材专属池（≥32），合计 ≥92 条。
class SentenceTemplates {
  /// 全部模板（通用池 + 题材专属池）。
  final List<String> templates;

  /// 构造模板库。
  const SentenceTemplates(this.templates);

  /// 随机取一条模板。
  String pick(SeededRandom rng) => rng.pick(templates);

  /// 按题材取模板库（通用池与专属池合并）。
  static SentenceTemplates forGenre(String genre) {
    final List<String> list = <String>[
      ..._common,
      ...(_byGenre[genre] ?? _byGenre['xuanhuan']!),
    ];
    return SentenceTemplates(list);
  }

