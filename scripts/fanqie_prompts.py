def first_screen_rewrite_prompt(content, genre, protagonist):
    """第 1~3 章的首屏强化：只改前 300 字，其余原样返回。"""
    return (
        f"下面是《{protagonist}》这本{genre}小说某一章的开头。番茄的完读率几乎全部押在前 300 字，"
        "请只重写前 300 字，做到：\n"
        "1) 主角在场、正在做事、有东西可失去；2) 第一句就有异常或压力；3) 第二段出现对白或动作冲突；\n"
        "4) 删掉所有背景交代与天气描写；5) 句子尽量 25 字内，段落不超过 3 行；\n"
        "6) 保留原有事件与人物名，不新增角色，不改变后文衔接。\n"
        "只输出改写后的开头（约 300 字），不要解释：\n\n"
        + content[:600]
    )


